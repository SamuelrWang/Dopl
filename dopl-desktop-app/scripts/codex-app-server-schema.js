'use strict';

// CAPTURE THE INSTALLED `codex app-server`'s PROTOCOL INTO THE COMPATIBILITY FIXTURE.
//
//   cd dopl-desktop-app && npm run codex:schema          write the fixture
//   cd dopl-desktop-app && npm run codex:schema -- --print   print it, write nothing
//
// 🔒 ⚠ **THIS SCRIPT IS THE ONLY SANCTIONED WAY THE FIXTURE GETS CONTENT** (U1,
// `docs/plans/2026-09-21-001-fix-codex-runtime-parity-plan.md`). The plan exists because 94
// targeted tests passed against SYNTHETIC fixtures while the adapter sent request shapes the
// installed CLI rejects. A hand-written fixture would rebuild that trap, so the fixture ships as
// an explicit `UNVERIFIED-PLACEHOLDER` and only a real handshake may replace it.
//
// 🔒 ⚠ **IT FAILS LOUDLY RATHER THAN WRITING AN EMPTY FIXTURE.** No binary, no answer, a refused
// binary — each is a non-zero exit with the reason on stderr and the file left exactly as it was.
// A script that quietly wrote `{}` would turn "we never measured this" into "we measured nothing
// there", which is the same lie in a different costume.
//
// ⚠ **WHAT IT STORES IS A SHAPE, NOT A TRANSCRIPT.** Every captured object is reduced to its key
// names and value TYPES (`shapeOf`), plus array lengths. Model ids are kept because the picker
// renders them and the contract suite asserts over them; nothing else keeps a value. Prompts,
// tokens, absolute paths outside the resolved binary and any auth material never enter this file
// because nothing here sends a turn or reads a credential.
//
// ⚠ **IT SPAWNS THROUGH `main/runtime/codex/client.js`**, which spawns the path
// `main/runtime/codex/resolve-bin.js` resolved. That is deliberate: a fixture generated by a
// DIFFERENT spawn path than the app uses would measure a binary the app may never run.

const fs = require('node:fs');
const path = require('node:path');
const { execFile } = require('node:child_process');

const client = require('../main/runtime/codex/client.js');
const resolveBin = require('../main/runtime/codex/resolve-bin.js');

const FIXTURE = path.join(__dirname, '..', 'test', 'fixtures', 'codex-app-server.json');
const HANDSHAKE_TIMEOUT_MS = 20000;
const HELP_TIMEOUT_MS = 10000;

// ── SHAPE REDUCTION ──────────────────────────────────────────────────────────────────────────

const MAX_DEPTH = 6;

/**
 * An object reduced to `{ key: "<type>" }`, recursively. Arrays become
 * `{ "[]": <shape of first element>, "length": n }`. ⚠ Scalars keep their TYPE, never their value.
 */
function shapeOf(value, depth) {
  const d = depth || 0;
  if (d > MAX_DEPTH) return '…';
  if (value === null) return 'null';
  if (Array.isArray(value)) {
    return { length: value.length, '[]': value.length ? shapeOf(value[0], d + 1) : 'empty' };
  }
  if (typeof value !== 'object') return typeof value;
  const out = {};
  for (const key of Object.keys(value).sort()) out[key] = shapeOf(value[key], d + 1);
  return out;
}

/**
 * Model rows, reduced to what the picker and the gate actually read.
 * ⚠ TOLERANT over the container key for the same reason `models.js › idsFrom` is: the spelling is
 * what this run is MEASURING, so assuming one would defeat the point. Whatever arrived is recorded
 * in `container`.
 */
function modelsFrom(result) {
  for (const key of ['models', 'data', 'items']) {
    if (result && Array.isArray(result[key])) return { container: key, rows: result[key] };
  }
  if (Array.isArray(result)) return { container: '(top-level array)', rows: result };
  return { container: null, rows: [] };
}

function modelRow(row) {
  if (typeof row === 'string') return { id: row, raw: 'string' };
  if (!row || typeof row !== 'object') return { id: null, raw: typeof row };
  const flag = row.isDefault !== undefined ? row.isDefault
    : (row.is_default !== undefined ? row.is_default : row.default);
  return {
    id: row.id || row.model || row.name || null,
    displayName: typeof row.displayName === 'string' ? row.displayName : null,
    isDefault: flag === true,
    keys: Object.keys(row).sort(),
  };
}

// ── THE CAPTURE ──────────────────────────────────────────────────────────────────────────────

function fail(message, code) {
  process.stderr.write(`\ncodex:schema — NOTHING WAS WRITTEN.\n  ${message}\n\n`);
  process.stderr.write(`  The fixture at ${path.relative(process.cwd(), FIXTURE)} is unchanged.\n`);
  process.stderr.write('  ⚠ Do not hand-fill it. A synthetic protocol shape is what this unit exists to prevent.\n\n');
  process.exit(code || 1);
}

function run(bin, args, timeout) {
  return new Promise((resolve) => {
    execFile(bin, args, { timeout, maxBuffer: 4 * 1024 * 1024 }, (err, stdout, stderr) => {
      resolve({ ok: !err, out: String(stdout || ''), err: String(stderr || ''), error: err ? err.message : null });
    });
  });
}

/** One bounded app-server session. ⚠ The child is closed on EVERY path, including a throw. */
async function withAppServer(fn) {
  const conn = client.connect({ args: [] });
  let timer = null;
  const budget = new Promise((_, reject) => {
    timer = setTimeout(
      () => reject(new Error(`the app-server did not finish the handshake within ${HANDSHAKE_TIMEOUT_MS}ms`)),
      HANDSHAKE_TIMEOUT_MS,
    );
  });
  try {
    return await Promise.race([Promise.resolve().then(() => fn(conn)), budget]);
  } finally {
    clearTimeout(timer);
    try { conn.close(); } catch (_) { /* best effort */ }
    await new Promise((done) => {
      const child = conn.child;
      if (!child || child.exitCode !== null) { done(); return; }
      const hard = setTimeout(() => { try { child.kill('SIGKILL'); } catch (_) { /* gone */ } }, 1500);
      const give = setTimeout(done, 3500);
      child.once('exit', () => { clearTimeout(hard); clearTimeout(give); done(); });
    });
  }
}

async function capture() {
  const found = resolveBin.resolveCodexBin();
  if (!found.ok) fail(found.reason, 2);

  const version = await run(found.path, ['--version'], HELP_TIMEOUT_MS);
  if (!version.ok) fail(`\`${found.path} --version\` failed: ${version.error}`, 2);
  const versionText = version.out.trim() || version.err.trim();

  const help = await run(found.path, ['app-server', '--help'], HELP_TIMEOUT_MS);

  const handshake = await withAppServer(async (conn) => {
    const out = { initialize: null, declaredMethods: null, modelList: null, errors: [] };
    const init = await conn.request('initialize', client.initializeParams(versionText));
    out.initialize = { shape: shapeOf(init), raw: null };
    // ⚠ NO PATH IS ASSUMED. Whatever the server offers that LOOKS like a method list is recorded
    // with the key it arrived under; when nothing does, `declaredMethods` stays null — which the
    // gate reads as `unverified-protocol`, not as `[]`.
    for (const key of ['methods', 'supportedMethods', 'capabilities']) {
      const value = init && init[key];
      if (Array.isArray(value) && value.every((v) => typeof v === 'string')) {
        out.declaredMethods = { key, names: value.slice().sort() };
        break;
      }
    }
    try {
      const list = await conn.request('model/list', {});
      const { container, rows } = modelsFrom(list);
      out.modelList = {
        shape: shapeOf(list),
        container,
        count: rows.length,
        models: rows.map(modelRow),
        defaults: rows.map(modelRow).filter((r) => r.isDefault).map((r) => r.id),
      };
    } catch (err) {
      out.errors.push({ method: 'model/list', message: (err && err.message) || String(err), code: (err && err.code) || null });
    }
    return out;
  });

  return {
    fixtureFormat: 'dopl:codex-app-server/1',
    status: 'MEASURED',
    statusNote: 'Captured from a real Codex CLI by scripts/codex-app-server-schema.js. Shapes are key names and value types; no prompt, token or transcript content is stored.',
    regenerate: 'cd dopl-desktop-app && npm run codex:schema',
    generatedBy: 'dopl-desktop-app/scripts/codex-app-server-schema.js',
    capturedAt: new Date().toISOString(),
    cli: {
      version: versionText,
      versionCommand: `${found.path} --version`,
      path: found.path,
      source: found.source,
    },
    help: {
      command: `${found.path} app-server --help`,
      text: help.ok ? help.out.trim().slice(0, 4000) : null,
    },
    handshake,
    doplRequires: {
      note: 'THIS BLOCK IS NOT A MEASUREMENT — it is Dopl\'s own requirement, mirrored from `main/runtime/codex/client.js` (REQUIRED_METHODS / REQUIRED_FACTS) so the contract suite can prove the two have not drifted.',
      methods: client.REQUIRED_METHODS.slice(),
      facts: client.REQUIRED_FACTS.map((f) => f.key),
    },
  };
}

// ── THE PIN THE OPERATOR HAS TO PASTE ────────────────────────────────────────────────────────

function advise(fixture) {
  const detected = fixture.cli.version;
  const pinned = client.SUPPORTED_CLI;
  const lines = ['', `codex:schema — measured ${detected} at ${fixture.cli.path} (${fixture.cli.source}).`];
  if (!pinned.min && !pinned.max) {
    const parsed = client.parseVersion(detected);
    const shown = parsed ? parsed.join('.') : String(detected);
    lines.push('');
    lines.push('⚠ `SUPPORTED_CLI` in main/runtime/codex/client.js is still UNPINNED, so the version');
    lines.push('  gate refuses nothing. Now that a real CLI has been measured, pin it:');
    lines.push('');
    lines.push(`      const SUPPORTED_CLI = Object.freeze({ min: '${shown}', max: null, measuredFrom: '${shown}' });`);
  }
  if (!fixture.handshake.declaredMethods) {
    lines.push('');
    lines.push('⚠ This app-server declared NO method list in `initialize`, so the gate can only');
    lines.push('  report `unverified-protocol` from a handshake. U3 must decide what else it reads.');
  }
  const defaults = (fixture.handshake.modelList && fixture.handshake.modelList.defaults) || [];
  if (defaults.length !== 1) {
    lines.push('');
    lines.push(`⚠ The model catalog declares ${defaults.length} defaults. The contract suite requires exactly one.`);
  }
  lines.push('');
  return lines.join('\n');
}

async function main() {
  const print = process.argv.includes('--print');
  const fixture = await capture();
  if (print) {
    process.stdout.write(`${JSON.stringify(fixture, null, 2)}\n`);
  } else {
    fs.writeFileSync(FIXTURE, `${JSON.stringify(fixture, null, 2)}\n`);
    process.stdout.write(`codex:schema — wrote ${path.relative(process.cwd(), FIXTURE)}\n`);
  }
  process.stdout.write(advise(fixture));
}

main().catch((err) => fail((err && err.message) || String(err), 1));
